"""Estimator diagnosis (2026-11-09): the CW-Q-rho pair loss is linear in the pair weights, so G=2/8/16 and the K=7
sparse-cross variant all target the SAME expected objective L_rho; they differ only as estimators.  With params and
data FIXED (checkpoint + replay window generated by its own eps-greedy policy, as in d1_kappa_noise.py), compute the
loss gradient for many batches under each estimator and compare: mean gradient (expectation equality), noise
(tr Cov, SNR), clipping (max_grad_norm 10) and the resulting Adam step (clip -> adam b1 .9 b2 .999 eps 1e-5).
Gradient (exact for the qcw all-pairs loss with delta = xi/(1-g)):  dL/dQ_k = -sum_j (W+W^T)_kj xi_kj/(1-g),
xi_kj = v_j u_k - v_k u_j (theory form), u_k = r + g(1-term) max_a Q(s'_k,a) - Q(s_k,a_k), v = 1 - g(1-term).
Approximation: target net (not saved) = online net; the cur_target/Amax/Bmin terms reduce to the theory form then.
usage: est_diag.py --ckpt X.pkl --jsonl run.jsonl --out res.json"""
import argparse, json, os, pickle, sys, time
import numpy as np
sys.path.insert(0, "/home/junweiluo/Stoix")
import jax, jax.numpy as jnp
from jax.flatten_util import ravel_pytree
import pgx


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", required=True); ap.add_argument("--jsonl", required=True); ap.add_argument("--out", required=True)
    ap.add_argument("--E", type=int, default=128); ap.add_argument("--T", type=int, default=782); ap.add_argument("--burn", type=int, default=300)
    ap.add_argument("--N", type=int, default=400); ap.add_argument("--m", type=int, default=512); ap.add_argument("--rho", type=float, default=0.5)
    ap.add_argument("--eps", type=float, default=0.1); ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--ests", default="G2,G8,G16,K7")
    a = ap.parse_args(); t0 = time.time()
    cfg = json.loads(open(a.jsonl).readline())["config"]
    game = cfg["env"]["scenario"]["name"]; gamma = float(cfg["system"]["gamma"]); clipn = float(cfg["system"]["max_grad_norm"])
    from stoix.systems.q_learning.ff_rpair import PairNet
    s = cfg["system"]
    env = pgx.make(game); env.sticky_action_prob = 0.1; A = int(env.num_actions)
    net = PairNet(num_actions=A, head=str(s["head"]), hidden=128, emb_dim=16, rank=int(s.get("pair_rank", 32)),
                  n_atoms=int(s.get("rc_atoms", 51)), vmax=float(s.get("rc_vmax", 20.0)), additive=False)
    params = jax.tree_util.tree_map(lambda x: x[0], pickle.load(open(a.ckpt, "rb")))
    Qall = lambda p, o: net.apply(p, o.astype(jnp.float32), method=PairNet.duel_comp_obs)[3]
    q = jax.jit(lambda o: Qall(params, o))
    step = jax.vmap(env.step); init = jax.vmap(env.init); E = a.E

    @jax.jit
    def run(key):
        k0, key = jax.random.split(key)
        st = init(jax.random.split(k0, E))

        def f(st, k):
            k1, k2, k3, k4 = jax.random.split(k, 4)
            qs = q(st.observation)
            act = jnp.where(jax.random.uniform(k1, (E,)) < a.eps, jax.random.randint(k2, (E,), 0, A), jnp.argmax(qs, -1))
            s2 = step(st, act, jax.random.split(k3, E))
            d = s2.terminated | s2.truncated
            out = (st.observation, act, qs[jnp.arange(E), act], s2.rewards[:, 0], s2.terminated.astype(jnp.float32), d,
                   jnp.max(q(s2.observation), -1))
            fresh = init(jax.random.split(k4, E))
            s3 = jax.tree_util.tree_map(lambda f_, o_: jnp.where(d.reshape((-1,) + (1,) * (o_.ndim - 1)), f_, o_), fresh, s2)
            return s3, out
        _, out = jax.lax.scan(f, st, jax.random.split(key, a.burn + a.T))
        return out
    obs, act, qsa, r, term, done, qn = [np.asarray(x)[a.burn:] for x in run(jax.random.PRNGKey(a.seed))]   # [T, E, ...]
    T = a.T
    sw = lambda x: np.swapaxes(x, 0, 1).reshape((E * T,) + x.shape[2:])          # flat index = e*T + t
    obs, act, qsa, r, term, done, qn = map(sw, (obs, act, qsa, r, term, done, qn))
    obs = jnp.asarray(obs.astype(np.uint8)); actj = jnp.asarray(act)
    v = 1 - gamma * (1 - term); u = r + gamma * (1 - term) * qn - qsa
    dn = done.reshape(E, T); ep = np.cumsum(dn, 1) - dn                          # trajectory segments per env row
    start = np.zeros((E, T), np.int64); length = np.zeros((E, T), np.int64)
    for e_ in range(E):
        ks, first, cnt = np.unique(ep[e_], return_index=True, return_counts=True)
        pos = np.searchsorted(ks, ep[e_])
        start[e_] = e_ * T + first[pos]; length[e_] = cnt[pos]
    start = start.ravel(); length = length.ravel(); NI = E * T
    rng = np.random.default_rng(a.seed + 1)

    def groups(G):
        n = a.m // G
        anc = rng.integers(0, NI, n)
        L = length[anc]; off = anc - start[anc]
        rr = rng.integers(0, np.maximum(L - 1, 1)[:, None], (n, G - 1))
        rr = rr + (rr >= off[:, None])
        part = np.where(L[:, None] > 1, start[anc][:, None] + rr, anc[:, None])
        return np.concatenate([anc[:, None], part], 1).reshape(-1)

    def wdense(idx, G):
        m = len(idx); grp = np.arange(m) // G
        distinct = idx[:, None] != idx[None, :]
        same = (grp[:, None] == grp[None, :]) & distinct; cross = (grp[:, None] != grp[None, :]) & distinct
        return (1 - a.rho) * same / max(same.sum(), 1) + a.rho * cross / max(cross.sum(), 1)

    def wsparse(idx, G, K):
        m = len(idx); n = m // G; grp = np.arange(m) // G
        blk = np.empty(n, np.int64); blk[rng.permutation(n)] = np.arange(n) // (K + 1)
        col = np.concatenate([rng.permutation(G) for _ in range(n)])
        cid = blk[grp] * G + col
        distinct = idx[:, None] != idx[None, :]
        same = (grp[:, None] == grp[None, :]) & distinct
        cross = (cid[:, None] == cid[None, :]) & (grp[:, None] != grp[None, :]) & distinct
        return (1 - a.rho) * same / max(same.sum(), 1) + a.rho * cross / max(cross.sum(), 1)

    def batch(est):
        if est[0] == "G":
            G = int(est[1:]); idx = groups(G); W = wdense(idx, G)
        else:
            K = int(est[1:]); idx = groups(K + 1); W = wsparse(idx, K + 1, K)
        Ws = W + W.T; ub, vb = u[idx], v[idx]
        dLdQ = -((Ws @ vb) * ub - (Ws @ ub) * vb) / (1 - gamma)
        return idx, dLdQ

    flat0, unrav = ravel_pytree(params); P = flat0.size

    @jax.jit
    def grad(idx, c):
        f = lambda p: jnp.sum(c * Qall(p, obs[idx])[jnp.arange(idx.shape[0]), actj[idx]])
        return ravel_pytree(jax.grad(f)(params))[0]

    ests = a.ests.split(","); R = {}; MU = {}; UB = {}
    for est in ests:
        S1 = np.zeros(P); S2 = np.zeros(P); C1 = np.zeros(P); C2 = np.zeros(P)
        m1 = np.zeros(P); m2 = np.zeros(P); usum = np.zeros(P); unorm = []; norms = []; ecoef = []; nwarm = 50
        for t in range(1, a.N + 1):
            idx, c = batch(est)
            g = np.asarray(grad(jnp.asarray(idx), jnp.asarray(c, jnp.float32)), np.float64)
            nrm = np.linalg.norm(g); norms.append(nrm); ecoef.append(np.abs(c).sum())
            gc = g * min(1.0, clipn / max(nrm, 1e-12))
            S1 += g; S2 += g * g; C1 += gc; C2 += gc * gc
            m1 = .9 * m1 + .1 * gc; m2 = .999 * m2 + .001 * gc * gc
            upd = (m1 / (1 - .9 ** t)) / (np.sqrt(m2 / (1 - .999 ** t)) + 1e-5)
            if t > nwarm:
                usum += upd; unorm.append(np.linalg.norm(upd))
        N = a.N; mu = S1 / N; trcov = (S2.sum() / N - (mu ** 2).sum()) * N / (N - 1)
        muc = C1 / N; sc = C2 / N
        MU[est] = mu; UB[est] = usum / (N - nwarm)
        var_p = (S2 / N - mu ** 2) * N / (N - 1); varc_p = (C2 / N - muc ** 2) * N / (N - 1)
        mu2u = mu ** 2 - var_p / N; muc2u = muc ** 2 - varc_p / N              # unbiased squared means
        R[est] = {"mu2_unb": float(mu2u.sum()), "snr_unb": float(mu2u.sum() / trcov),
                  "adam_signal_unb": float(np.sum(muc2u / (np.sqrt(sc) + 1e-5))),          # E[descent per step] ~ sum mu^2/sqrt(E g^2)
                  "adam_rms_upd": float(np.sqrt(np.sum(sc / (np.sqrt(sc) + 1e-5) ** 2))),
                  "gnorm_mean": float(np.mean(norms)), "gnorm_med": float(np.median(norms)), "clip_frac": float(np.mean(np.array(norms) > clipn)),
                  "mu_norm": float(np.linalg.norm(mu)), "trcov": float(trcov), "snr": float((mu ** 2).sum() / trcov),
                  "abs_dLdQ_sum": float(np.mean(ecoef)),
                  "adam_descent_analytic": float(np.sum(muc ** 2 / (np.sqrt(sc) + 1e-5))),
                  "adam_mean_dir_norm_analytic": float(np.linalg.norm(muc / (np.sqrt(sc) + 1e-5))),
                  "adam_upd_norm_sim": float(np.mean(unorm)), "adam_mean_upd_norm_sim": float(np.linalg.norm(UB[est]))}
    ref = np.mean([MU[e] for e in ests], 0); rn = ref / np.linalg.norm(ref)
    for e in ests:
        R[e]["adam_proj_ref_sim"] = float(UB[e] @ rn)        # Adam step along the pooled expected gradient (per unit lr)
        R[e]["cos_mu_ref"] = float(MU[e] @ rn / np.linalg.norm(MU[e]))
        R[e]["cos_adam_ref"] = float(UB[e] @ rn / np.linalg.norm(UB[e]))
    for e in ests:                                           # expectation equality vs G8: z ~ 1 if equal means
        if e != "G8":
            R[e]["z_mu_vs_G8"] = float(np.linalg.norm(MU[e] - MU["G8"]) / np.sqrt((R[e]["trcov"] + R["G8"]["trcov"]) / a.N))
            R[e]["cos_mu_vs_G8"] = float(MU[e] @ MU["G8"] / np.linalg.norm(MU[e]) / np.linalg.norm(MU["G8"]))
    out = {"ckpt": os.path.basename(a.ckpt), "game": game, "P": int(P), "term_frac": float(term.mean()),
           "u_sd": float(u.std()), "mean_traj_len": float(length.mean()), "N": a.N, "est": R, "wall": time.time() - t0}
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True); json.dump(out, open(a.out, "w")); print(json.dumps(out)[:3000])


if __name__ == "__main__":
    main()
