"""D1 (2026-11-09): how much noise / bias does CW-Q-rho's implicit level correction inject into terminal samples?

qcw loss (ff_rpair.duel_all_pairs, head=qcw): delta_ij = xi_ij / (1-g),  xi_ij = v_j u_i - v_i u_j  (theory form),
u_i = r_i + g(1-d_i) max_a Q(s'_i, a) - Q(s_i, a_i),  v_i = 1 - g(1-d_i)  (1 for terminal, 1-g for others),
pair weights W = rho_weight_matrix (same-group distinct items share 1-rho, cross-group distinct items share rho).
Gradient coefficient on Q(s_i, a_i):  e_i = sum_j w_ij xi_ij = (sum_j w_ij v_j) * (u_i - v_i * kappa_i),
  kappa_i = sum_j w_ij u_j / sum_j w_ij v_j   (w = W + W^T, local level estimate from i's partners).
At the CW fixed point u_i = eta_i + kappa v_i, so the residual seen by sample i is eta_i + v_i (kappa - kappa_i):
terminal samples (v=1) receive the full level-estimation error, non-terminal ones 1-g = 1% of it.
Measured on a replay window generated by the checkpoint itself (eps .1, sticky .1, 128 envs x 782 steps = buffer
100k, episodes split at termination), batches built like same_traj_batch (n_grp groups of G items of one stored
trajectory, anchor uniform).  Target net is not saved -> online net used for the bootstrap (approximation).
Reported for terminal items in batches:
  sd_eta      sd of (u_i - kappa_glob)            (TD noise a terminal sample carries anyway; DQN analogue)
  sd_kap      sd of (kappa_i - kappa_glob)        (extra noise injected by the level correction)        -> M1
  bias_same   mean(kappa_i^same - kappa_glob)     (same-trajectory part of kappa_i; bias of rho pairing)  -> M2
  bias_cross  mean(kappa_i^cross - kappa_glob)
  bias_full   mean(kappa_i - kappa_glob)
kappa_glob = mean(u)/mean(v) over the whole window.  Also u/kappa stats for DQN checkpoints (kappa = 0 there).
usage: d1_kappa_noise.py --ckpt X.pkl --jsonl run.jsonl --out res.json [--G 8]
"""
import argparse, json, os, pickle, sys, time
import numpy as np
sys.path.insert(0, "/home/junweiluo/Stoix"); sys.path.insert(0, "/home/junweiluo/Stoix/scripts_rdqn/ranking")
import jax, jax.numpy as jnp  # noqa: E402
from rank_minatar import build_q  # noqa: E402
import pgx  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", required=True); ap.add_argument("--jsonl", required=True); ap.add_argument("--out", required=True)
    ap.add_argument("--G", type=int, default=0); ap.add_argument("--E", type=int, default=128); ap.add_argument("--T", type=int, default=782)
    ap.add_argument("--burn", type=int, default=300); ap.add_argument("--n_batches", type=int, default=400)
    ap.add_argument("--m", type=int, default=512); ap.add_argument("--rho", type=float, default=0.5)
    ap.add_argument("--eps", type=float, default=0.1); ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args(); t0 = time.time()
    cfg = json.loads(open(a.jsonl).readline())["config"]
    game = cfg["env"]["scenario"]["name"]; gamma = float(cfg["system"]["gamma"])
    G = a.G or int(cfg["system"].get("st_group", 8))
    kind = "pair" if "_qcw_" in os.path.basename(a.ckpt) else "dqn"
    env = pgx.make(game); env.sticky_action_prob = 0.1; A = int(env.num_actions)
    params = jax.tree_util.tree_map(lambda x: x[0], pickle.load(open(a.ckpt, "rb")))
    qf = build_q(cfg, A, kind); q = jax.jit(lambda o: qf(params, o.astype(jnp.float32)))
    step = jax.vmap(env.step); init = jax.vmap(env.init); E = a.E

    @jax.jit
    def run(key):
        k0, key = jax.random.split(key)
        s = init(jax.random.split(k0, E))

        def f(s, k):
            k1, k2, k3, k4 = jax.random.split(k, 4)
            qs = q(s.observation)
            act = jnp.where(jax.random.uniform(k1, (E,)) < a.eps, jax.random.randint(k2, (E,), 0, A), jnp.argmax(qs, -1))
            s2 = step(s, act, jax.random.split(k3, E))
            d = s2.terminated | s2.truncated
            qn = q(s2.observation)
            out = (qs[jnp.arange(E), act], s2.rewards[:, 0], s2.terminated.astype(jnp.float32), d, jnp.max(qn, -1))
            fresh = init(jax.random.split(k4, E))
            s3 = jax.tree_util.tree_map(lambda f_, o_: jnp.where(d.reshape((-1,) + (1,) * (o_.ndim - 1)), f_, o_), fresh, s2)
            return s3, out
        _, out = jax.lax.scan(f, s, jax.random.split(key, a.burn + a.T))
        return out
    qsa, r, term, done, qn = [np.asarray(x)[a.burn:].T for x in run(jax.random.PRNGKey(a.seed))]   # [E, T]
    v = 1 - gamma * (1 - term)
    u = r + gamma * (1 - term) * qn - qsa
    kap_g = u.mean() / v.mean()
    # trajectories inside the window: episode id per env (split after done)
    ep = np.cumsum(done, 1) - done
    rng = np.random.default_rng(a.seed)
    n_grp = a.m // G
    flat_u, flat_v, flat_t = u.ravel(), v.ravel(), term.ravel()
    seg = {}                                                         # (env, ep) -> flat indices
    for e_ in range(E):
        for k in np.unique(ep[e_]):
            idx = np.where(ep[e_] == k)[0] + e_ * a.T
            seg[(e_, k)] = idx
    rec = {"eta": [], "kap": [], "same": [], "cross": [], "td": []}; nterm = 0
    for _ in range(a.n_batches):
        ae = rng.integers(0, E, n_grp); at = rng.integers(0, a.T, n_grp)
        idx = []
        for e_, t_ in zip(ae, at):
            s_ = seg[(e_, ep[e_, t_])]; anc = e_ * a.T + t_
            others = s_[s_ != anc]
            pick = rng.choice(others, G - 1, replace=len(others) < G - 1) if len(others) else np.full(G - 1, anc)
            idx.append(np.concatenate([[anc], pick]))
        idx = np.concatenate(idx)
        grp = np.arange(a.m) // G
        distinct = idx[:, None] != idx[None, :]
        same = (grp[:, None] == grp[None, :]) & distinct; cross = (grp[:, None] != grp[None, :]) & distinct
        Ws = (1 - a.rho) * same / max(same.sum(), 1); Wc = a.rho * cross / max(cross.sum(), 1)
        ub, vb, tb = flat_u[idx], flat_v[idx], flat_t[idx]
        ti = np.where(tb > 0)[0]
        if len(ti) == 0:
            continue
        nterm += len(ti)
        W0 = Ws + Wc                                                  # terminal-decoupled variant (rho_weight_matrix_td)
        rmv = (grp[:, None] == grp[None, :]) & ((tb[:, None] > 0) | (tb[None, :] > 0))
        Wrm = np.where(rmv, W0, 0.0); keep = W0 - Wrm
        crow = np.where(cross, keep, 0.0).sum(1)
        Wtd = np.where(cross, keep * (1 + Wrm.sum(1) / np.maximum(crow, 1e-30))[:, None], keep)
        for nm, W in (("kap", W0), ("same", Ws), ("cross", Wc), ("td", Wtd)):
            w = (W + W.T)[ti]
            den = w @ vb
            ok = den > 0
            rec[nm].append(np.where(ok, (w @ ub) / np.where(ok, den, 1), np.nan) - kap_g)
        rec["eta"].append(ub[ti] - kap_g)
    R = {k: np.concatenate(v_) for k, v_ in rec.items()}
    res = {"ckpt": os.path.basename(a.ckpt), "game": game, "kind": kind, "G": G, "kappa_glob": float(kap_g),
           "term_frac": float(term.mean()), "u_mean": float(u.mean()), "u_sd": float(u.std()),
           "u_term_mean": float(u[term > 0].mean()) if term.sum() else None,
           "q_mean": float(qsa.mean()), "n_term_in_batches": int(nterm), "term_per_batch": nterm / a.n_batches,
           "sd_eta": float(np.nanstd(R["eta"])), "sd_kap": float(np.nanstd(R["kap"])),
           "sd_kap_same": float(np.nanstd(R["same"])), "sd_kap_cross": float(np.nanstd(R["cross"])),
           "bias_full": float(np.nanmean(R["kap"])), "bias_same": float(np.nanmean(R["same"])),
           "bias_cross": float(np.nanmean(R["cross"])),
           "corr_eta_kap": float(np.corrcoef(R["eta"][np.isfinite(R["kap"])], R["kap"][np.isfinite(R["kap"])])[0, 1]),
           "sd_resid_term": float(np.nanstd(R["eta"] - R["kap"])), "sd_kap_td": float(np.nanstd(R["td"])), "bias_td": float(np.nanmean(R["td"])), "sd_resid_term_td": float(np.nanstd(R["eta"] - R["td"])), "wall": time.time() - t0}
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True); json.dump(res, open(a.out, "w")); print(json.dumps(res))


if __name__ == "__main__":
    main()
