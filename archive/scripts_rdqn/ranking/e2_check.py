"""2026-11-09 check of the expected CW-rho update decomposition and strength of the trajectory weight (E2).

Exact batch quantities (qcw loss, rho kernel W, w = W + W^T):
  omega_i = sum_j w_ij v_j                      (sample weight: e_i = omega_i * (u_i - v_i * kappa_i))
Predicted expectation over partner draws (m items, G per group, rho):
  m/2 * omega_i ~= (1-rho) * vbar_{T\\i} + rho * vbar_batch,
  vbar_{T\\i} = (1-g) + g * 1{T terminated, i not the terminal item} / (n_T - 1)
(T = i's stored trajectory inside the replay window, n_T its stored length).
Also reports, per game / checkpoint, how strongly E2 reweights the batch:
  w_rel = omega_i / mean(omega) ; share of total weight on items of terminated trajectories vs their item share;
  weight ratio between items of short (n_T < 100) and long (n_T >= 300) terminated trajectories.
Replay window generated by the checkpoint itself (eps .1, sticky .1, 128 envs x 782 steps) as in d1_kappa_noise.py.
usage: e2_check.py --ckpt X.pkl --jsonl run.jsonl --out res.json"""
import argparse, json, os, pickle, sys
import numpy as np
sys.path.insert(0, "/home/junweiluo/Stoix"); sys.path.insert(0, "/home/junweiluo/Stoix/scripts_rdqn/ranking")
import jax, jax.numpy as jnp  # noqa: E402
from rank_minatar import build_q  # noqa: E402
import pgx  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--ckpt", required=True); ap.add_argument("--jsonl", required=True); ap.add_argument("--out", required=True)
ap.add_argument("--E", type=int, default=128); ap.add_argument("--T", type=int, default=782); ap.add_argument("--burn", type=int, default=300)
ap.add_argument("--n_batches", type=int, default=200); ap.add_argument("--m", type=int, default=512); ap.add_argument("--G", type=int, default=8)
ap.add_argument("--rho", type=float, default=0.5); ap.add_argument("--seed", type=int, default=11)
a = ap.parse_args()
cfg = json.loads(open(a.jsonl).readline())["config"]; game = cfg["env"]["scenario"]["name"]; g = float(cfg["system"]["gamma"])
kind = "pair" if "_qcw_" in os.path.basename(a.ckpt) else "dqn"
env = pgx.make(game); env.sticky_action_prob = 0.1; A = int(env.num_actions)
params = jax.tree_util.tree_map(lambda x: x[0], pickle.load(open(a.ckpt, "rb")))
qf = build_q(cfg, A, kind); q = jax.jit(lambda o: qf(params, o.astype(jnp.float32)))
step, init, E = jax.vmap(env.step), jax.vmap(env.init), a.E


@jax.jit
def run(key):
    k0, key = jax.random.split(key); s = init(jax.random.split(k0, E))

    def f(s, k):
        k1, k2, k3, k4 = jax.random.split(k, 4)
        act = jnp.where(jax.random.uniform(k1, (E,)) < 0.1, jax.random.randint(k2, (E,), 0, A), jnp.argmax(q(s.observation), -1))
        s2 = step(s, act, jax.random.split(k3, E)); d = s2.terminated | s2.truncated
        fresh = init(jax.random.split(k4, E))
        s3 = jax.tree_util.tree_map(lambda f_, o_: jnp.where(d.reshape((-1,) + (1,) * (o_.ndim - 1)), f_, o_), fresh, s2)
        return s3, (s2.terminated.astype(jnp.float32), d)
    _, out = jax.lax.scan(f, s, jax.random.split(key, a.burn + a.T)); return out
term, done = [np.asarray(x)[a.burn:].T for x in run(jax.random.PRNGKey(a.seed))]
v = 1 - g * (1 - term)
ep = np.cumsum(done, 1) - done
seg, info = {}, {}
for e_ in range(E):
    for k in np.unique(ep[e_]):
        idx = np.where(ep[e_] == k)[0] + e_ * a.T; seg[(e_, k)] = idx
        info[(e_, k)] = (len(idx), bool(term.ravel()[idx[-1]] > 0))
flat_v, flat_t = v.ravel(), term.ravel()
nT = np.zeros(E * a.T); termT = np.zeros(E * a.T, bool)
for kk, idx in seg.items():
    nT[idx] = info[kk][0]; termT[idx] = info[kk][1]
rng = np.random.default_rng(a.seed); n_grp = a.m // a.G
OM, PR, NT, TT, IT = [], [], [], [], []
for _ in range(a.n_batches):
    ae = rng.integers(0, E, n_grp); at = rng.integers(0, a.T, n_grp); idx = []
    for e_, t_ in zip(ae, at):
        s_ = seg[(e_, ep[e_, t_])]; anc = e_ * a.T + t_; others = s_[s_ != anc]
        pick = rng.choice(others, a.G - 1, replace=len(others) < a.G - 1) if len(others) else np.full(a.G - 1, anc)
        idx.append(np.concatenate([[anc], pick]))
    idx = np.concatenate(idx); grp = np.arange(a.m) // a.G
    distinct = idx[:, None] != idx[None, :]
    same = (grp[:, None] == grp[None, :]) & distinct; cross = (grp[:, None] != grp[None, :]) & distinct
    W = (1 - a.rho) * same / max(same.sum(), 1) + a.rho * cross / max(cross.sum(), 1); w = W + W.T
    vb = flat_v[idx]; om = w @ vb
    n_ = nT[idx]; tt = termT[idx]; it = flat_t[idx] > 0
    vT = (1 - g) + g * (tt & ~it) / np.maximum(n_ - 1, 1)
    PR.append((1 - a.rho) * vT + a.rho * vb.mean()); OM.append(om * a.m / 2); NT.append(n_); TT.append(tt); IT.append(it)
OM, PR, NT, TT, IT = map(np.concatenate, (OM, PR, NT, TT, IT))
wr = OM / OM.mean()
short = TT & (NT < 100) & ~IT; long_ = TT & (NT >= 300) & ~IT
res = {"ckpt": os.path.basename(a.ckpt), "game": game,
       "pred_corr": float(np.corrcoef(OM, PR)[0, 1]), "pred_ratio_mean": float(OM.mean() / PR.mean()),
       "pred_mae_rel": float(np.mean(np.abs(OM - PR)) / OM.mean()),
       "item_share_term_traj": float(TT.mean()), "weight_share_term_traj": float(wr[TT].sum() / wr.sum()),
       "w_rel_terminal_item": float(wr[IT].mean()) if IT.any() else None,
       "w_rel_short_term": float(wr[short].mean()) if short.any() else None,
       "w_rel_long_term": float(wr[long_].mean()) if long_.any() else None,
       "w_rel_unfinished": float(wr[~TT].mean()) if (~TT).any() else None,
       "w_rel_p10_p90": [float(np.percentile(wr, 10)), float(np.percentile(wr, 90))], "w_rel_max": float(wr.max()),
       "median_nT_term": float(np.median(NT[TT])) if TT.any() else None, "frac_short_items": float(short.mean())}
os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True); json.dump(res, open(a.out, "w")); print(json.dumps(res))
